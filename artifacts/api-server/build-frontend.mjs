import { spawnSync } from "node:child_process";
import { cpSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const artifactDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(artifactDir, "../..");
const frontendDir = path.resolve(artifactDir, "../nexus-admissions");
const frontendDist = path.join(frontendDir, "dist/public");
const publicDir = path.join(artifactDir, "public");

const pnpmCommand = `${process.platform === "win32" ? "pnpm.cmd" : "pnpm"} --dir "${frontendDir}" run build`;

const res = spawnSync(pnpmCommand, {
  stdio: "inherit",
  cwd: repoRoot,
  shell: true,
});

if (res.status !== 0) {
  process.exit(res.status ?? 1);
}

rmSync(publicDir, { recursive: true, force: true });
cpSync(frontendDist, publicDir, { recursive: true, force: true });
console.log(`Frontend assets copied to ${publicDir}`);

function collectAssets(dir, base, out) {
  for (const entry of readdirSync(dir)) {
    const entryPath = path.join(dir, entry);
    const relEntry = path.join(base, entry).split(path.sep).join("/");
    if (statSync(entryPath).isDirectory()) {
      collectAssets(entryPath, relEntry, out);
    } else {
      out[`/${relEntry}`] = readFileSync(entryPath, "utf8");
    }
  }
}

const spaAssets = {};
collectAssets(frontendDist, "", spaAssets);

const generatedModule = path.join(artifactDir, "src", "spa-assets.generated.ts");
writeFileSync(
  generatedModule,
  `// Generated by build-frontend.mjs. Do not edit by hand.\n` +
    `export const SPA_ASSETS: Record<string, string> = ` +
    `${JSON.stringify(spaAssets)};\n`,
);
console.log(`Embedded ${Object.keys(spaAssets).length} SPA assets in ${generatedModule}`);